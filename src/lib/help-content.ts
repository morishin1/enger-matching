export function helpFor(pathname: string): HelpDoc {
  const found = HELP_DOCS
    .filter((h) => pathname.startsWith(h.match))
    .sort((a, b) => b.match.length - a.match.length)[0];
  return found?.doc ?? DEFAULT_HELP;
}
